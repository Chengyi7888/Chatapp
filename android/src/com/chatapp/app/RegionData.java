    private static void add(String province, String cities) {
        Map<String, List<String>> m = new LinkedHashMap<>();
        for (String c : cities.split(";")) {
            String[] parts = c.split("\\|");
            String city = parts[0];
            List<String> ds = new ArrayList<>();
            if (parts.length > 1 && !parts[1].isEmpty() && !parts[1].equals("-")) {
                for (String d : parts[1].split(",")) ds.add(d);
            }
            m.put(city, ds);
        }
        DATA.put(province, m);
    }

    /** 省列表, 第一位 "-" 表示未填写 */
    public static List<String> provinces() {
        List<String> list = new ArrayList<>();
        list.add("-");
        list.addAll(DATA.keySet());
        return list;
    }

