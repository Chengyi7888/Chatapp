    public static List<String> cities(String province) {
        if (province == null || province.equals("-")) {
            List<String> d = new ArrayList<>();
            d.add("-");
            return d;
        }
        Map<String, List<String>> m = DATA.get(province);
        if (m == null) {
            List<String> d = new ArrayList<>();
            d.add("-");
            return d;
        }
        return new ArrayList<>(m.keySet());
    }

    /** 区列表, 无区(如香港/东莞)时返回 ["-"] */
    public static List<String> districts(String province, String city) {
        if (city == null || city.equals("-") || province == null || province.equals("-")) {
            List<String> d = new ArrayList<>();
            d.add("-");
            return d;
        }
        Map<String, List<String>> m = DATA.get(province);
        if (m == null) {
            List<String> d = new ArrayList<>();
            d.add("-");
            return d;
        }
        List<String> ds = m.get(city);
        if (ds == null || ds.isEmpty()) {
            List<String> d = new ArrayList<>();
            d.add("-");
            return d;
        }
        return ds;
    }
